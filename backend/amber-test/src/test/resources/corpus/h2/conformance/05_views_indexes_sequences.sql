-- Views, materialized-like, indexes, sequences, domains, constants
CREATE VIEW sales.v_customer_orders AS SELECT c.customer_id, c.display_name, COUNT(o.order_id) AS n FROM sales.customer c LEFT JOIN sales.order_header o ON o.customer_id = c.customer_id GROUP BY c.customer_id, c.display_name;
CREATE OR REPLACE VIEW sales.v_active (id, name) AS SELECT customer_id, display_name FROM sales.customer WHERE is_active;
CREATE FORCE VIEW sales.v_future AS SELECT * FROM sales.not_yet_created;
ALTER VIEW sales.v_active RECOMPILE;
DROP VIEW IF EXISTS sales.v_future;
CREATE INDEX idx_order_customer ON sales.order_header (customer_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_customer_email ON sales.customer (email);
CREATE INDEX idx_order_multi ON sales.order_header (customer_id ASC, ordered_at DESC);
CREATE HASH INDEX idx_cache_v ON audit.lookup_cache (v);
CREATE SPATIAL INDEX idx_geo ON sales.type_zoo (c_geo);
ALTER INDEX sales.idx_order_multi RENAME TO idx_order_cust_date;
DROP INDEX IF EXISTS sales.idx_order_cust_date;
CREATE SEQUENCE sales.invoice_seq START WITH 1000 INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999 CACHE 20 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS sales.batch_seq AS BIGINT;
SELECT NEXT VALUE FOR sales.invoice_seq;
SELECT NEXTVAL('sales.invoice_seq'), CURRVAL('sales.invoice_seq');
SELECT CURRENT VALUE FOR sales.invoice_seq;
INSERT INTO audit.event_log (id, msg) VALUES (NEXT VALUE FOR sales.batch_seq, 'start');
ALTER SEQUENCE sales.invoice_seq RESTART WITH 5000;
ALTER SEQUENCE sales.invoice_seq INCREMENT BY 5;
DROP SEQUENCE IF EXISTS sales.batch_seq;
CREATE DOMAIN email_address AS VARCHAR(255) CHECK (POSITION('@', VALUE) > 1);
CREATE DOMAIN IF NOT EXISTS positive_amount AS DECIMAL(12, 2) DEFAULT 0 CHECK (VALUE >= 0);
CREATE TABLE sales.contact (id INT PRIMARY KEY, mail email_address, credit positive_amount);
ALTER DOMAIN positive_amount SET DEFAULT 1;
DROP DOMAIN IF EXISTS email_address CASCADE;
CREATE CONSTANT IF NOT EXISTS sales.max_lines VALUE 500;
SELECT sales.max_lines;
DROP CONSTANT sales.max_lines;
CREATE SYNONYM sales.cust FOR sales.customer;
DROP SYNONYM sales.cust;
CREATE MATERIALIZED VIEW sales.mv_totals AS SELECT customer_id, SUM(total) AS t FROM sales.order_header GROUP BY customer_id;
REFRESH MATERIALIZED VIEW sales.mv_totals;
DROP MATERIALIZED VIEW sales.mv_totals;
