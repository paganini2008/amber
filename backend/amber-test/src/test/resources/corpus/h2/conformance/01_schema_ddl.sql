-- Schemas, tables, constraints, identity, generated columns, data types
CREATE SCHEMA IF NOT EXISTS sales;
CREATE SCHEMA audit AUTHORIZATION sa;
SET SCHEMA sales;
CREATE TABLE sales.customer (
  customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(100) NOT NULL,
  email VARCHAR(255) UNIQUE,
  balance NUMERIC(12, 2) DEFAULT 0 NOT NULL CHECK (balance >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  is_active BOOLEAN DEFAULT TRUE,
  notes CHARACTER LARGE OBJECT,
  avatar BINARY LARGE OBJECT,
  uid UUID DEFAULT RANDOM_UUID()
);
CREATE TABLE sales.product (
  product_id INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 10),
  sku CHARACTER VARYING(32) NOT NULL,
  price DECIMAL(10, 2),
  tax_rate REAL DEFAULT 0.2,
  price_with_tax DECIMAL(12, 2) GENERATED ALWAYS AS (price * (1 + tax_rate)),
  tags VARCHAR(20) ARRAY[10],
  attrs JSON,
  weight DOUBLE PRECISION,
  launched DATE,
  open_time TIME,
  CONSTRAINT pk_product PRIMARY KEY (product_id),
  CONSTRAINT uq_product_sku UNIQUE (sku)
);
CREATE TABLE sales.order_header (
  order_id BIGINT AUTO_INCREMENT PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  ordered_at TIMESTAMP DEFAULT LOCALTIMESTAMP,
  status VARCHAR(10) DEFAULT 'NEW' CHECK (status IN ('NEW', 'PAID', 'SHIPPED')),
  total NUMERIC(14, 2),
  FOREIGN KEY (customer_id) REFERENCES sales.customer (customer_id) ON DELETE CASCADE
);
CREATE TABLE sales.order_line (
  order_id BIGINT,
  line_no INT,
  product_id INT REFERENCES sales.product,
  qty SMALLINT NOT NULL,
  amount NUMERIC(12, 2),
  PRIMARY KEY (order_id, line_no),
  CONSTRAINT fk_line_order FOREIGN KEY (order_id) REFERENCES sales.order_header (order_id) ON DELETE CASCADE ON UPDATE RESTRICT
);
CREATE TABLE sales.type_zoo (
  c_tinyint TINYINT, c_bigint BIGINT, c_decfloat DECFLOAT(20), c_float FLOAT(24),
  c_char CHAR(5), c_varchar_ic VARCHAR_IGNORECASE(30), c_binary BINARY(16), c_varbinary VARBINARY(64),
  c_interval INTERVAL DAY TO SECOND, c_ym INTERVAL YEAR TO MONTH,
  c_tstz TIMESTAMP(3) WITH TIME ZONE, c_timetz TIME WITH TIME ZONE,
  c_enum ENUM('LOW', 'MEDIUM', 'HIGH'), c_geo GEOMETRY, c_java JAVA_OBJECT, c_row ROW(x INT, y INT)
);
CREATE CACHED TABLE IF NOT EXISTS audit.event_log (id BIGINT PRIMARY KEY, msg VARCHAR(1000));
CREATE MEMORY TABLE audit.lookup_cache (k VARCHAR(50) PRIMARY KEY, v VARCHAR(200));
CREATE TABLE audit.event_copy AS SELECT * FROM audit.event_log WITH NO DATA;
CREATE TABLE audit.event_snapshot (id, msg) AS SELECT id, msg FROM audit.event_log;
ALTER TABLE sales.customer ADD COLUMN phone VARCHAR(30);
ALTER TABLE sales.customer ADD COLUMN IF NOT EXISTS loyalty_tier INT DEFAULT 0;
ALTER TABLE sales.customer ALTER COLUMN phone SET DATA TYPE VARCHAR(40);
ALTER TABLE sales.customer ALTER COLUMN phone RENAME TO phone_number;
ALTER TABLE sales.customer ALTER COLUMN loyalty_tier SET DEFAULT 1;
ALTER TABLE sales.customer ALTER COLUMN loyalty_tier SET NOT NULL;
ALTER TABLE sales.customer ALTER COLUMN customer_id RESTART WITH 1000;
ALTER TABLE sales.customer ADD CONSTRAINT chk_tier CHECK (loyalty_tier BETWEEN 0 AND 5);
ALTER TABLE sales.customer DROP CONSTRAINT chk_tier;
ALTER TABLE sales.customer DROP COLUMN IF EXISTS phone_number;
ALTER TABLE audit.event_copy RENAME TO event_backup;
