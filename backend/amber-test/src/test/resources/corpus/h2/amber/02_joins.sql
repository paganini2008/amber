SELECT * FROM a INNER JOIN b ON a.id = b.a_id;
SELECT * FROM a JOIN b ON a.id = b.a_id JOIN c ON c.b_id = b.id;
SELECT * FROM a LEFT JOIN b ON a.id = b.a_id;
SELECT * FROM a LEFT OUTER JOIN b ON a.id = b.a_id;
SELECT * FROM a RIGHT JOIN b ON a.id = b.a_id;
SELECT * FROM a RIGHT OUTER JOIN b ON a.id = b.a_id;
SELECT * FROM a FULL JOIN b ON a.id = b.id;
SELECT * FROM a FULL OUTER JOIN b ON a.id = b.id;
SELECT * FROM a CROSS JOIN b;
SELECT * FROM a NATURAL JOIN b;
SELECT * FROM a NATURAL LEFT JOIN b;
SELECT * FROM a NATURAL INNER JOIN b;
SELECT * FROM a JOIN b USING (id);
SELECT * FROM a LEFT JOIN b USING (id, version);
SELECT * FROM a, b WHERE a.id = b.id;
SELECT * FROM a AS x JOIN b AS y ON x.id = y.id;
SELECT * FROM a x JOIN b y ON x.id = y.id LEFT JOIN c z ON z.id = y.c_id;
SELECT * FROM (a JOIN b ON a.id = b.id) LEFT JOIN c ON c.id = a.id;
SELECT * FROM a JOIN (b JOIN c ON b.id = c.id) ON a.id = b.id;
SELECT * FROM orders o JOIN (SELECT customer_id, MAX(amount) m FROM orders GROUP BY customer_id) mx ON mx.customer_id = o.customer_id AND mx.m = o.amount;
SELECT * FROM a, LATERAL (SELECT * FROM b WHERE b.a_id = a.id FETCH FIRST 1 ROW ONLY) lb;
SELECT * FROM test USE INDEX (idx_test_name) WHERE name = 'x';
SELECT * FROM SYSTEM_RANGE(1, 10);
SELECT x FROM SYSTEM_RANGE(1, 100, 5) r;
SELECT * FROM CSVREAD('data/test.csv') AS csv;
SELECT * FROM UNNEST(ARRAY[1, 2, 3]) WITH ORDINALITY AS t(v, n);
SELECT * FROM UNNEST(ARRAY['a', 'b'], ARRAY[1, 2]) AS t(s, n);
