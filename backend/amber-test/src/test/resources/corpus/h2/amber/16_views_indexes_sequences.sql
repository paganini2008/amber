-- Views, materialized views, indexes, sequences
CREATE VIEW v_test AS SELECT * FROM test;
CREATE OR REPLACE VIEW v_test (id, label) AS SELECT id, name FROM test WHERE active;
CREATE FORCE VIEW v_missing AS SELECT * FROM table_created_later;
CREATE OR REPLACE FORCE VIEW IF NOT EXISTS PUBLIC.v2 AS WITH c AS (SELECT 1 x) SELECT * FROM c;
CREATE VIEW v_union AS SELECT a FROM t1 UNION ALL SELECT a FROM t2 ORDER BY 1;
ALTER VIEW v_test RECOMPILE;
ALTER VIEW IF EXISTS v_test RENAME TO v_test2;
DROP VIEW v_test2;
DROP VIEW IF EXISTS v_union CASCADE;
DROP VIEW v_missing RESTRICT;
CREATE MATERIALIZED VIEW mv_sales AS SELECT region, SUM(amount) total FROM sales GROUP BY region;
CREATE OR REPLACE MATERIALIZED VIEW IF NOT EXISTS mv_sales2 (region, total) AS SELECT region, SUM(amount) FROM sales GROUP BY region;
REFRESH MATERIALIZED VIEW mv_sales;
DROP MATERIALIZED VIEW IF EXISTS mv_sales2;
CREATE INDEX idx_test_name ON test (name);
CREATE INDEX IF NOT EXISTS idx_multi ON PUBLIC.test (a ASC, b DESC NULLS LAST);
CREATE UNIQUE INDEX uq_test_code ON test (code);
CREATE UNIQUE NULLS NOT DISTINCT INDEX uq_test_code2 ON test (code2) INCLUDE (name, value);
CREATE HASH INDEX idx_hash ON test (id);
CREATE UNIQUE HASH INDEX idx_uhash ON test (code);
CREATE SPATIAL INDEX idx_geom ON shapes (geom);
CREATE PRIMARY KEY ON test (id);
CREATE INDEX ON test (status);
ALTER INDEX idx_test_name RENAME TO idx_test_full_name;
ALTER INDEX IF EXISTS PUBLIC.idx_multi RENAME TO idx_multi2;
DROP INDEX idx_test_full_name;
DROP INDEX IF EXISTS PUBLIC.idx_multi2;
CREATE SEQUENCE seq_id;
CREATE SEQUENCE IF NOT EXISTS PUBLIC.seq_order START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE seq_big AS BIGINT START WITH 1 INCREMENT BY 50 MINVALUE 1 MAXVALUE 9223372036854775807 NO CYCLE CACHE 100;
CREATE SEQUENCE seq_small AS SMALLINT NO MINVALUE NO MAXVALUE NO CACHE;
CREATE SEQUENCE seq_ora START WITH 1 NOMINVALUE NOMAXVALUE NOCYCLE NOCACHE NOORDER;
CREATE SEQUENCE seq_neg START WITH -1 INCREMENT BY -1 CYCLE ORDER;
ALTER SEQUENCE seq_id RESTART WITH 500;
