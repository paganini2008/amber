    c_geometry2 GEOMETRY(POINT),
    c_geometry3 GEOMETRY(POLYGON Z, 4326),
    c_json JSON,
    c_json2 JSON(1000),
    c_uuid UUID,
    c_array INTEGER ARRAY,
    c_array2 VARCHAR(10) ARRAY[5],
    c_row ROW(a INT, b VARCHAR(10)),
    c_row2 ROW(x DOUBLE PRECISION, y DOUBLE PRECISION) ARRAY,
    c_identity_type IDENTITY
);
SELECT CAST(x AS INTERVAL DAY TO SECOND), CAST(y AS ROW(a INT)), CAST(z AS INT ARRAY[3]), CAST(w AS CHARACTER VARYING(10)) FROM t;
SELECT CAST(a AS DOUBLE PRECISION), CAST(b AS BINARY LARGE OBJECT), CAST(c AS NUMERIC(5)), CAST(d AS DECFLOAT(10)) FROM t;
CREATE SEQUENCE s_typed AS DECIMAL(20, 0);
