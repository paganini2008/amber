-- ORDER BY, OFFSET / FETCH, LIMIT
SELECT * FROM t ORDER BY a;
SELECT * FROM t ORDER BY a ASC, b DESC;
SELECT * FROM t ORDER BY a NULLS FIRST, b DESC NULLS LAST;
SELECT * FROM t ORDER BY 1, 2 DESC;
SELECT * FROM t ORDER BY LOWER(name), id + 1;
SELECT * FROM t ORDER BY a OFFSET 10 ROWS;
SELECT * FROM t ORDER BY a OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY;
SELECT * FROM t ORDER BY a OFFSET 1 ROW FETCH FIRST ROW ONLY;
SELECT * FROM t ORDER BY a FETCH FIRST 10 ROWS ONLY;
SELECT * FROM t ORDER BY a FETCH FIRST 10 PERCENT ROWS WITH TIES;
SELECT * FROM t ORDER BY a FETCH FIRST 10 ROWS ONLY OFFSET 5 ROWS;
SELECT * FROM t LIMIT 10;
SELECT * FROM t LIMIT 10 OFFSET 20;
