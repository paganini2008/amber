GRANT ALL ON TABLE test TO app_user;
GRANT ALL PRIVILEGES ON SCHEMA app TO app_user;
GRANT SELECT ON SCHEMA PUBLIC TO PUBLIC;
GRANT ALTER ANY SCHEMA TO app_user;
GRANT readonly TO app_user;
GRANT readonly, writer TO PUBLIC;
REVOKE INSERT ON test FROM writer;
REVOKE ALL ON SCHEMA app FROM app_user;
REVOKE SELECT, UPDATE ON TABLE test FROM PUBLIC;
REVOKE ALTER ANY SCHEMA FROM app_user;
REVOKE readonly FROM app_user;
