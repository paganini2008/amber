-- CREATE TABLE / ALTER TABLE with MariaDB options
CREATE OR REPLACE TABLE products (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  sku VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL,
  price DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  price_with_tax DECIMAL(10,2) AS (price * 1.2) PERSISTENT,
  name_upper VARCHAR(200) GENERATED ALWAYS AS (UPPER(name)) VIRTUAL,
  attrs JSON CHECK (JSON_VALID(attrs)),
  attrs2 LONGTEXT CHECK (JSON_VALID(attrs2)),
  ip INET6, ip4 INET4, uid UUID,
  hidden_note VARCHAR(50) INVISIBLE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  status ENUM('new', 'old') DEFAULT 'new' COMMENT 'lifecycle',
  CONSTRAINT chk_name CHECK (CHAR_LENGTH(name) > 0),
  INDEX ix_name (name) COMMENT 'by name',
  UNIQUE KEY uq_sku_hash (name) USING HASH
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci PAGE_COMPRESSED=1 COMMENT='products';
