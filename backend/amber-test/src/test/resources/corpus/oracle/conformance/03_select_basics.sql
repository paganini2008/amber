-- Oracle conformance: SELECT basics
SELECT * FROM customers;
SELECT DISTINCT region FROM customers;
SELECT UNIQUE region FROM customers;
SELECT customer_id, UPPER(family_name) AS lname, given_name fname FROM customers WHERE region IN ('EU', 'NA') ORDER BY lname DESC NULLS LAST, fname;
SELECT * FROM orders WHERE order_date BETWEEN DATE '2024-01-01' AND DATE '2024-12-31';
SELECT * FROM customers WHERE family_name LIKE 'Sm%' ESCAPE '\';
SELECT * FROM customers WHERE REGEXP_LIKE(email, '^[a-z]+@example\.com$', 'i');
SELECT * FROM orders WHERE amount > ANY (100, 200, 300);
SELECT * FROM orders WHERE amount >= ALL (SELECT amount FROM refunds);
SELECT * FROM orders WHERE (customer_id, status) IN ((1, 'OPEN'), (2, 'SHIPPED'));
SELECT * FROM orders WHERE status <> 'X' AND status != 'Y' AND status ^= 'Z';
SELECT * FROM orders ORDER BY amount DESC FETCH FIRST 10 ROWS ONLY;
SELECT * FROM orders ORDER BY amount DESC OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY;
SELECT * FROM orders ORDER BY amount DESC FETCH FIRST 5 PERCENT ROWS WITH TIES;
SELECT * FROM orders SAMPLE (10);
SELECT * FROM orders SAMPLE BLOCK (5) SEED (42);
SELECT * FROM orders AS OF TIMESTAMP (SYSTIMESTAMP - INTERVAL '10' MINUTE);
SELECT * FROM orders AS OF SCN 1234567;
SELECT versions_starttime, versions_operation, order_id FROM orders VERSIONS BETWEEN TIMESTAMP MINVALUE AND MAXVALUE;
SELECT * FROM orders WHERE order_id = 10 FOR UPDATE;
SELECT * FROM orders WHERE order_id = 10 FOR UPDATE OF status NOWAIT;
SELECT * FROM orders WHERE status = 'NEW' FOR UPDATE SKIP LOCKED;
SELECT * FROM orders FOR UPDATE WAIT 5;
SELECT order_id, CASE status WHEN 'N' THEN 'New' WHEN 'S' THEN 'Shipped' ELSE 'Other' END AS status_text FROM orders;
SELECT employee_id, manager_id, LEVEL, SYS_CONNECT_BY_PATH(family_name, '/') AS path FROM employees START WITH manager_id IS NULL CONNECT BY PRIOR employee_id = manager_id ORDER SIBLINGS BY family_name;
SELECT employee_id, CONNECT_BY_ROOT family_name AS root_name, CONNECT_BY_ISLEAF FROM employees CONNECT BY NOCYCLE PRIOR employee_id = manager_id START WITH employee_id = 100;
SELECT LEVEL AS n FROM dual CONNECT BY LEVEL <= 31;
SELECT * FROM TABLE(my_pkg.get_rows(10));
SELECT COLUMN_VALUE FROM TABLE(sys.odcinumberlist(1, 2, 3));
SELECT t.* FROM orders t WHERE t.amount IS NOT NULL AND NOT (t.status = 'X');
SELECT order_id FROM orders PARTITION (p_2024);
SELECT order_id FROM orders SUBPARTITION (sp_2024_eu);
SELECT order_id FROM orders PARTITION FOR (DATE '2024-03-01');
SELECT LISTAGG(product_name, ', ') WITHIN GROUP (ORDER BY product_name) FROM products;
SELECT LISTAGG(DISTINCT category, ';' ON OVERFLOW TRUNCATE '...' WITH COUNT) WITHIN GROUP (ORDER BY category) FROM products;
SELECT customer_id, amount FROM orders WHERE amount > 100 AND ROWNUM < 50 ORDER BY 2 DESC;
SELECT 1 FROM dual WHERE EXISTS (SELECT 1 FROM orders);
SELECT CURSOR(SELECT order_id FROM orders o WHERE o.customer_id = c.customer_id) FROM customers c;
SELECT TREAT(obj AS shape_t).area() FROM shapes;
