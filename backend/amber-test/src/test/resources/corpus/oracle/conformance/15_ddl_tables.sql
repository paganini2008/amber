-- Oracle conformance: CREATE/ALTER/DROP TABLE, constraints, partitioning, identity, virtual columns
CREATE TABLE regions (
  region_id   NUMBER(4)     CONSTRAINT regions_pk PRIMARY KEY,
  region_name VARCHAR2(50)  NOT NULL CONSTRAINT regions_name_uk UNIQUE
);
CREATE TABLE customers (
  customer_id NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1000 INCREMENT BY 1 CACHE 50),
  name        VARCHAR2(200 CHAR) NOT NULL,
  email       VARCHAR2(320),
  region_id   NUMBER(4) REFERENCES regions (region_id) ON DELETE SET NULL,
  status      VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE', 'CLOSED')),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT customers_pk PRIMARY KEY (customer_id),
  CONSTRAINT customers_email_uk UNIQUE (email) USING INDEX TABLESPACE idx_ts
);
CREATE TABLE order_lines (
  order_id   NUMBER NOT NULL,
  line_no    NUMBER(3) NOT NULL,
  qty        NUMBER(10) DEFAULT ON NULL 1,
  unit_price NUMBER(12,2),
  line_total NUMBER(14,2) GENERATED ALWAYS AS (qty * unit_price) VIRTUAL,
  line_tax   AS (ROUND(qty * unit_price * 0.2, 2)),
  CONSTRAINT order_lines_pk PRIMARY KEY (order_id, line_no),
  CONSTRAINT order_lines_fk FOREIGN KEY (order_id) REFERENCES orders (order_id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE ids_by_default (id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, val VARCHAR2(10));
CREATE TABLE orders_part (
  order_id   NUMBER,
  order_date DATE NOT NULL,
  region     VARCHAR2(10),
  amount     NUMBER(12,2)
)
PARTITION BY RANGE (order_date)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
  PARTITION p_before_2024 VALUES LESS THAN (DATE '2024-01-01'),
  PARTITION p_2024_01 VALUES LESS THAN (DATE '2024-02-01') TABLESPACE data_2024
)
ENABLE ROW MOVEMENT;
CREATE TABLE sales_list (id NUMBER, region VARCHAR2(10))
PARTITION BY LIST (region) (
  PARTITION p_eu VALUES ('DE', 'FR', 'IT'),
  PARTITION p_na VALUES ('US', 'CA'),
  PARTITION p_other VALUES (DEFAULT)
);
CREATE TABLE events_hash (id NUMBER, payload VARCHAR2(400)) PARTITION BY HASH (id) PARTITIONS 8 STORE IN (ts1, ts2);
CREATE TABLE sales_comp (id NUMBER, sale_date DATE, region VARCHAR2(10))
PARTITION BY RANGE (sale_date) SUBPARTITION BY LIST (region)
SUBPARTITION TEMPLATE (SUBPARTITION sp_eu VALUES ('EU'), SUBPARTITION sp_rest VALUES (DEFAULT))
(PARTITION p2024 VALUES LESS THAN (DATE '2025-01-01'), PARTITION pmax VALUES LESS THAN (MAXVALUE));
