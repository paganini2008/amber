-- Oracle conformance: temporary tables
CREATE GLOBAL TEMPORARY TABLE gtt_orders (order_id NUMBER, amount NUMBER) ON COMMIT DELETE ROWS;
CREATE GLOBAL TEMPORARY TABLE gtt_session (k VARCHAR2(30), v VARCHAR2(4000)) ON COMMIT PRESERVE ROWS;
CREATE GLOBAL TEMPORARY TABLE gtt_copy ON COMMIT PRESERVE ROWS AS SELECT * FROM orders WHERE 1 = 0;
CREATE PRIVATE TEMPORARY TABLE ora$ptt_stage (id NUMBER, val VARCHAR2(100)) ON COMMIT DROP DEFINITION;
CREATE PRIVATE TEMPORARY TABLE ora$ptt_sess (id NUMBER) ON COMMIT PRESERVE DEFINITION;
CREATE PRIVATE TEMPORARY TABLE ora$ptt_ctas ON COMMIT PRESERVE DEFINITION AS SELECT order_id FROM orders;
INSERT INTO gtt_orders SELECT order_id, amount FROM orders WHERE region = 'EU';
INSERT INTO ora$ptt_stage (id, val) VALUES (1, 'a');
SELECT * FROM gtt_orders g JOIN ora$ptt_stage p ON p.id = g.order_id;
CREATE INDEX gtt_orders_ix ON gtt_orders (order_id);
TRUNCATE TABLE gtt_session;
DROP TABLE gtt_orders;
DROP TABLE ora$ptt_sess;
CREATE GLOBAL TEMPORARY TABLE gtt_dur (id NUMBER) ON COMMIT PRESERVE ROWS TABLESPACE temp_ts;
