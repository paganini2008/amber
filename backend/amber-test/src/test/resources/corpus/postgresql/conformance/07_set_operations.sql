SELECT id FROM a UNION SELECT id FROM b;
SELECT id FROM a UNION ALL SELECT id FROM b;
SELECT id FROM a INTERSECT SELECT id FROM b;
SELECT id FROM a INTERSECT ALL SELECT id FROM b;
SELECT id FROM a EXCEPT SELECT id FROM b;
SELECT id FROM a EXCEPT ALL SELECT id FROM b;
SELECT id FROM a UNION SELECT id FROM b ORDER BY id LIMIT 5;
(SELECT id FROM a ORDER BY id LIMIT 3) UNION ALL (SELECT id FROM b ORDER BY id DESC LIMIT 3);
SELECT id FROM a UNION (SELECT id FROM b INTERSECT SELECT id FROM c);
((SELECT 1) UNION (SELECT 2)) EXCEPT (SELECT 2);
SELECT 1 UNION VALUES (2), (3);
SELECT * FROM (SELECT id FROM a UNION SELECT id FROM b) u;
WITH x AS (SELECT 1 AS v UNION SELECT 2) SELECT v FROM x EXCEPT SELECT 1;
