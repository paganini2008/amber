CREATE SCHEMA rpt AUTHORIZATION rptowner DATA CAPTURE NONE
    CREATE TABLE rpt.daily (d DATE NOT NULL, total DECIMAL(15, 2))
    CREATE VIEW rpt.v_daily AS SELECT d, total FROM rpt.daily
    CREATE INDEX rpt.ix_daily ON rpt.daily (d)
    COMMENT ON TABLE rpt.daily IS 'Daily totals'
    GRANT SELECT ON rpt.v_daily TO PUBLIC;
