CREATE FUNCTION app.gen_rows (n INTEGER) RETURNS TABLE (i INTEGER)
    LANGUAGE SQL
BEGIN
    DECLARE k INTEGER DEFAULT 1;
    WHILE k <= n DO
        PIPE (k);
        SET k = k + 1;
    END WHILE;
    RETURN;
END;
