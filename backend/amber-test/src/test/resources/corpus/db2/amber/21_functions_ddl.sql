CREATE FUNCTION app.tax (p_amount DECIMAL(15, 2)) RETURNS DECIMAL(15, 2)
    LANGUAGE SQL DETERMINISTIC NO EXTERNAL ACTION CONTAINS SQL
    RETURN p_amount * 0.19;
CREATE OR REPLACE FUNCTION app.display_nm (first VARCHAR(50), last VARCHAR(50))
    RETURNS VARCHAR(101)
    SPECIFIC app.full_name_v1
    LANGUAGE SQL
    DETERMINISTIC
    NO EXTERNAL ACTION
    CALLED ON NULL INPUT
    RETURN TRIM(first) || ' ' || TRIM(last);
CREATE FUNCTION app.orders_of (p_cust INTEGER)
    RETURNS TABLE (order_id BIGINT, amount DECIMAL(15, 2))
    LANGUAGE SQL READS SQL DATA NO EXTERNAL ACTION NOT DETERMINISTIC
    RETURN SELECT order_id, amount FROM app.orders WHERE customer_id = p_cust;
CREATE FUNCTION app.order_count (p_cust INTEGER) RETURNS INTEGER
    LANGUAGE SQL READS SQL DATA
    RETURN (SELECT COUNT(*) FROM app.orders WHERE customer_id = p_cust);
CREATE FUNCTION app.business_days (p_from DATE, p_to DATE) RETURNS INTEGER
    LANGUAGE SQL DETERMINISTIC NO EXTERNAL ACTION
BEGIN ATOMIC
    DECLARE v_days INTEGER DEFAULT 0;
    DECLARE v_d DATE;
    SET v_d = p_from;
    WHILE v_d <= p_to DO
        IF DAYOFWEEK(v_d) NOT IN (1, 7) THEN
            SET v_days = v_days + 1;
        END IF;
        SET v_d = v_d + 1 DAY;
    END WHILE;
    RETURN v_days;
END;
CREATE OR REPLACE FUNCTION app.compiled_fn (p INT DEFAULT 5) RETURNS VARCHAR(20)
    LANGUAGE SQL
BEGIN
    DECLARE v VARCHAR(20);
    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION SET v = 'error';
    SELECT name INTO v FROM app.lookup WHERE id = p;
    RETURN v;
END;
