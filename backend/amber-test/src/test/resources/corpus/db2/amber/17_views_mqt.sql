CREATE VIEW app.v_orders AS SELECT order_id, amount FROM app.orders WHERE status <> 'C';
CREATE OR REPLACE VIEW app.v_orders (id, amt) AS SELECT order_id, amount FROM app.orders;
CREATE VIEW app.v_checked AS SELECT * FROM app.orders WHERE amount > 0 WITH CHECK OPTION;
CREATE VIEW app.v_cascaded AS SELECT * FROM app.v_checked WHERE status = 'N' WITH CASCADED CHECK OPTION;
CREATE VIEW app.v_local AS SELECT * FROM app.v_checked WITH LOCAL CHECK OPTION;
CREATE VIEW app.v_cte AS WITH x AS (SELECT a FROM t) SELECT a FROM x UNION SELECT b FROM u;
CREATE TABLE app.mqt_sales AS (
    SELECT store_id, sale_date, SUM(amount) AS total, COUNT(*) AS cnt FROM app.fact_sales GROUP BY store_id, sale_date
) DATA INITIALLY DEFERRED REFRESH DEFERRED ENABLE QUERY OPTIMIZATION MAINTAINED BY SYSTEM IN ts_data;
CREATE TABLE app.mqt_imm (store_id, total, cnt) AS (
    SELECT store_id, SUM(amount), COUNT(*) FROM app.fact_sales GROUP BY store_id
) DATA INITIALLY DEFERRED REFRESH IMMEDIATE;
CREATE TABLE app.mqt_user AS (SELECT a, b FROM t) DATA INITIALLY DEFERRED REFRESH DEFERRED MAINTAINED BY USER DISABLE QUERY OPTIMIZATION;
CREATE SUMMARY TABLE app.sum1 AS (SELECT a, COUNT(*) AS c FROM t GROUP BY a) DATA INITIALLY DEFERRED REFRESH DEFERRED;
REFRESH TABLE app.mqt_sales;
REFRESH TABLE app.mqt_sales, app.mqt_imm ALLOW READ ACCESS NOT INCREMENTAL;
REFRESH TABLE app.mqt_sales INCREMENTAL;
SET INTEGRITY FOR app.mqt_imm IMMEDIATE CHECKED;
SET INTEGRITY FOR app.mqt_imm MATERIALIZED QUERY IMMEDIATE UNCHECKED;
