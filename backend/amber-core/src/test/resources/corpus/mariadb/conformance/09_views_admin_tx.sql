CREATE OR REPLACE VIEW v_active AS SELECT id, email FROM customers WHERE status = 'active';
CREATE VIEW IF NOT EXISTS v_totals (customer_id, total) AS SELECT customer_id, SUM(amount) FROM orders GROUP BY customer_id;
CREATE ALGORITHM=MERGE SQL SECURITY INVOKER VIEW v_big AS SELECT * FROM orders WHERE amount > 1000 WITH CHECK OPTION;
CREATE VIEW v_with AS WITH t AS (SELECT 1 AS x) SELECT x FROM t;
ALTER VIEW v_active AS SELECT id, email, name FROM customers WHERE status = 'active';
DROP VIEW IF EXISTS v_big, v_with;
