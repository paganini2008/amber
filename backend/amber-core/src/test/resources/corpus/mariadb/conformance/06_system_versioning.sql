CREATE TABLE room_bookings (
  room_id INT NOT NULL,
  guest VARCHAR(100),
  date_from DATE NOT NULL,
  date_to DATE NOT NULL,
  PERIOD FOR stay (date_from, date_to),
  UNIQUE (room_id, stay WITHOUT OVERLAPS)
);
