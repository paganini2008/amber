-- Oracle conformance: views and materialized views
CREATE VIEW v_open_orders AS SELECT order_id, amount FROM orders WHERE status = 'OPEN';
CREATE OR REPLACE VIEW v_open_orders (id, amt) AS SELECT order_id, amount FROM orders WHERE status = 'OPEN' WITH CHECK OPTION CONSTRAINT v_open_orders_chk;
CREATE OR REPLACE FORCE VIEW v_future AS SELECT * FROM not_yet_created;
CREATE OR REPLACE NOFORCE EDITIONABLE VIEW v_ed AS SELECT 1 x FROM dual;
CREATE VIEW v_ro AS SELECT * FROM orders WITH READ ONLY;
CREATE OR REPLACE VIEW hr.v_emp_dept BEQUEATH DEFINER AS SELECT e.family_name, d.dept_name FROM hr.employees e JOIN hr.departments d ON d.dept_id = e.dept_id;
ALTER VIEW v_open_orders COMPILE;
DROP VIEW v_future;
DROP VIEW v_ed CASCADE CONSTRAINTS;
CREATE MATERIALIZED VIEW mv_sales_by_region
  BUILD IMMEDIATE
  REFRESH FAST ON COMMIT
  ENABLE QUERY REWRITE
AS SELECT region, COUNT(*) cnt, SUM(amount) total FROM orders GROUP BY region;
CREATE MATERIALIZED VIEW mv_daily
  TABLESPACE mv_ts
  PARALLEL 4
  BUILD DEFERRED
  REFRESH COMPLETE ON DEMAND START WITH SYSDATE NEXT SYSDATE + 1
AS SELECT TRUNC(order_date) d, SUM(amount) s FROM orders GROUP BY TRUNC(order_date);
CREATE MATERIALIZED VIEW mv_remote REFRESH FORCE ON DEMAND AS SELECT * FROM orders@hq_link;
CREATE MATERIALIZED VIEW LOG ON orders WITH ROWID, SEQUENCE (region, amount) INCLUDING NEW VALUES;
ALTER MATERIALIZED VIEW mv_daily REFRESH COMPLETE;
ALTER MATERIALIZED VIEW mv_sales_by_region COMPILE;
DROP MATERIALIZED VIEW LOG ON orders;
DROP MATERIALIZED VIEW mv_remote;
DROP MATERIALIZED VIEW mv_daily PRESERVE TABLE;
CREATE OR REPLACE VIEW v_json AS SELECT JSON_OBJECT('id' VALUE order_id) j FROM orders;
CREATE OR REPLACE VIEW v_union AS SELECT order_id FROM orders UNION ALL SELECT order_id FROM archive_orders;
