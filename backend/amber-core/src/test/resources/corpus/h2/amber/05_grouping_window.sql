-- GROUP BY, HAVING, QUALIFY, WINDOW, window functions and frames
SELECT dept, COUNT(*) FROM emp GROUP BY dept;
SELECT dept, job, SUM(sal) FROM emp GROUP BY dept, job HAVING SUM(sal) > 1000;
SELECT dept, job, SUM(sal) FROM emp GROUP BY GROUPING SETS ((dept, job), (dept), ());
SELECT dept, job, SUM(sal), GROUPING(dept, job) FROM emp GROUP BY ROLLUP (dept, job);
SELECT dept, job, SUM(sal) FROM emp GROUP BY CUBE (dept, job);
SELECT dept, job, SUM(sal) FROM emp GROUP BY dept, ROLLUP (job);
SELECT COUNT(*) FROM emp GROUP BY ();
SELECT YEAR(hired), COUNT(*) FROM emp GROUP BY YEAR(hired) HAVING COUNT(*) > 2 ORDER BY 1;
SELECT name, ROW_NUMBER() OVER (ORDER BY sal DESC) AS rn FROM emp;
SELECT name, RANK() OVER (PARTITION BY dept ORDER BY sal DESC) FROM emp;
SELECT name, DENSE_RANK() OVER (PARTITION BY dept ORDER BY sal DESC NULLS LAST) FROM emp;
SELECT name, sal, SUM(sal) OVER (PARTITION BY dept ORDER BY hired ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) running FROM emp;
SELECT name, AVG(sal) OVER (ORDER BY hired ROWS BETWEEN 2 PRECEDING AND 2 FOLLOWING) FROM emp;
SELECT name, SUM(sal) OVER (ORDER BY hired RANGE BETWEEN INTERVAL '30' DAY PRECEDING AND CURRENT ROW) FROM emp;
SELECT name, COUNT(*) OVER (ORDER BY grade GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING EXCLUDE CURRENT ROW) FROM emp;
SELECT name, SUM(sal) OVER (ORDER BY hired ROWS UNBOUNDED PRECEDING EXCLUDE TIES) FROM emp;
SELECT name, SUM(sal) OVER (ORDER BY hired ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING EXCLUDE NO OTHERS) FROM emp;
SELECT name, SUM(sal) OVER (ORDER BY hired ROWS 3 PRECEDING EXCLUDE GROUP) FROM emp;
SELECT name, LAG(sal, 1, 0) OVER (PARTITION BY dept ORDER BY hired), LEAD(sal) OVER w FROM emp WINDOW w AS (PARTITION BY dept ORDER BY hired);
SELECT name, FIRST_VALUE(sal) IGNORE NULLS OVER w, LAST_VALUE(sal) RESPECT NULLS OVER w FROM emp
    WINDOW w AS (ORDER BY hired ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING);
SELECT NTH_VALUE(sal, 2) FROM FIRST OVER (ORDER BY sal) FROM emp;
SELECT NTH_VALUE(sal, 2) FROM LAST IGNORE NULLS OVER (ORDER BY sal) FROM emp;
SELECT NTILE(4) OVER (ORDER BY sal), PERCENT_RANK() OVER (ORDER BY sal), CUME_DIST() OVER (ORDER BY sal) FROM emp;
SELECT RATIO_TO_REPORT(sal) OVER (PARTITION BY dept) FROM emp;
SELECT name, SUM(sal) OVER w2 FROM emp WINDOW w1 AS (PARTITION BY dept), w2 AS (w1 ORDER BY hired);
SELECT name, dept FROM emp QUALIFY ROW_NUMBER() OVER (PARTITION BY dept ORDER BY sal DESC) = 1;
SELECT dept, COUNT(*) FILTER (WHERE sal > 1000) AS rich, COUNT(*) AS all_count FROM emp GROUP BY dept;
SELECT SUM(sal) FILTER (WHERE dept = 10) OVER (ORDER BY hired) FROM emp;
SELECT COUNT(DISTINCT dept), SUM(ALL sal) FROM emp;
SELECT LISTAGG(name, ', ') WITHIN GROUP (ORDER BY name) FROM emp;
SELECT dept, LISTAGG(DISTINCT name, ';' ON OVERFLOW TRUNCATE '...' WITH COUNT) WITHIN GROUP (ORDER BY name) FROM emp GROUP BY dept;
SELECT LISTAGG(name, ',' ON OVERFLOW ERROR) WITHIN GROUP (ORDER BY name DESC) FILTER (WHERE active) FROM emp;
SELECT PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY sal), PERCENTILE_DISC(0.9) WITHIN GROUP (ORDER BY sal DESC) FROM emp;
SELECT MODE() WITHIN GROUP (ORDER BY dept) FROM emp;
SELECT ARRAY_AGG(name ORDER BY name DESC) FROM emp;
SELECT ARRAY_AGG(DISTINCT dept ORDER BY dept) FILTER (WHERE dept IS NOT NULL) FROM emp;
SELECT GROUP_CONCAT(name ORDER BY id SEPARATOR '|') FROM emp;
SELECT RANK(5000) WITHIN GROUP (ORDER BY sal) FROM emp;
SELECT ANY_VALUE(name), BIT_AND_AGG(flags), EVERY(active), BOOL_OR(active), MEDIAN(sal), STDDEV_POP(sal), VAR_SAMP(sal) FROM emp;
SELECT JSON_ARRAYAGG(name ORDER BY name), JSON_OBJECTAGG(name: sal) FROM emp;
SELECT JSON_OBJECTAGG(KEY name VALUE sal ABSENT ON NULL WITH UNIQUE KEYS) FROM emp;
SELECT HISTOGRAM(dept), ENVELOPE(geom) FROM emp;
