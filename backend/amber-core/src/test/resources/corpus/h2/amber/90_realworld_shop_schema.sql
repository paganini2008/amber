-- =====================================================================
-- Online shop: schema setup (sequences, domains, tables, constraints,
-- indexes, views, comments, seed data)
-- =====================================================================
SET MODE REGULAR;
SET NON_KEYWORDS VALUE, KEY;

CREATE SCHEMA IF NOT EXISTS shop AUTHORIZATION sa;
SET SCHEMA shop;

CREATE DOMAIN IF NOT EXISTS shop.email_t AS VARCHAR(320)
    CHECK (VALUE LIKE '%_@_%._%');
CREATE DOMAIN IF NOT EXISTS shop.money_t AS NUMERIC(19, 4) DEFAULT 0
    CONSTRAINT money_not_negative CHECK (VALUE >= 0);

CREATE SEQUENCE IF NOT EXISTS shop.customer_seq START WITH 1000 INCREMENT BY 1 CACHE 32;
CREATE SEQUENCE IF NOT EXISTS shop.order_seq AS BIGINT START WITH 1 INCREMENT BY 1 NO CYCLE;

CREATE TABLE IF NOT EXISTS shop.customer (
    id            BIGINT DEFAULT NEXT VALUE FOR shop.customer_seq PRIMARY KEY,
    email         shop.email_t NOT NULL,
    display_name  VARCHAR(200) NOT NULL,
    status        VARCHAR(16) DEFAULT 'ACTIVE' NOT NULL,
    type          VARCHAR(16),
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE ON UPDATE CURRENT_TIMESTAMP,
    preferences   JSON,
    tags          VARCHAR(30) ARRAY[20],
    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT chk_customer_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED'))
);

CREATE TABLE IF NOT EXISTS shop.address (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT NOT NULL,
    kind         ENUM('BILLING', 'SHIPPING') NOT NULL,
    line1        VARCHAR(200) NOT NULL,
    line2        VARCHAR(200),
    city         VARCHAR(100) NOT NULL,
    zip          VARCHAR(20),
    country      CHAR(2) NOT NULL,
    location     GEOMETRY(POINT, 4326),
    CONSTRAINT fk_address_customer FOREIGN KEY (customer_id)
        REFERENCES shop.customer (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS shop.product (
    id          INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    sku         VARCHAR(40) NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description CHARACTER LARGE OBJECT,
    price       shop.money_t NOT NULL,
    vat_rate    DECIMAL(5, 2) DEFAULT 19.00 NOT NULL,
    gross_price NUMERIC(19, 4) GENERATED ALWAYS AS (price * (1 + vat_rate / 100)),
    active      BOOLEAN DEFAULT TRUE NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (sku)
);

CREATE TABLE IF NOT EXISTS shop.orders (
    id           BIGINT DEFAULT NEXT VALUE FOR shop.order_seq NOT NULL,
    customer_id  BIGINT NOT NULL REFERENCES shop.customer (id),
    order_date   DATE DEFAULT CURRENT_DATE NOT NULL,
    status       VARCHAR(16) DEFAULT 'NEW' NOT NULL,
    total        shop.money_t,
    note         VARCHAR(1000),
    CONSTRAINT pk_orders PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS shop.order_line (
    order_id    BIGINT NOT NULL,
    line_no     SMALLINT NOT NULL,
    product_id  INTEGER NOT NULL,
    qty         INTEGER NOT NULL CHECK (qty > 0),
    unit_price  NUMERIC(19, 4) NOT NULL,
    discount    NUMERIC(5, 2) DEFAULT 0,
    PRIMARY KEY (order_id, line_no),
    FOREIGN KEY (order_id) REFERENCES shop.orders (id) ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES shop.product (id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS shop.setting (
    key    VARCHAR(100) PRIMARY KEY,
    value  VARCHAR(4000),
    user   VARCHAR(100),
    date   DATE
);

CREATE INDEX IF NOT EXISTS idx_customer_name ON shop.customer (display_name);
CREATE INDEX IF NOT EXISTS idx_orders_customer_date ON shop.orders (customer_id, order_date DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_name ON shop.product (name);
CREATE SPATIAL INDEX IF NOT EXISTS idx_address_location ON shop.address (location);

ALTER TABLE shop.orders ADD CONSTRAINT IF NOT EXISTS chk_order_status
    CHECK (status IN ('NEW', 'PAID', 'SHIPPED', 'CANCELLED'));
ALTER TABLE shop.orders ADD COLUMN IF NOT EXISTS shipped_at TIMESTAMP AFTER status;
ALTER TABLE shop.customer ALTER COLUMN display_name SET DATA TYPE VARCHAR(300);

CREATE OR REPLACE VIEW shop.v_order_summary AS
SELECT o.id AS order_id,
       c.display_name AS customer,
       o.order_date,
       COUNT(ol.line_no) AS lines,
       SUM(ol.qty * ol.unit_price * (1 - ol.discount / 100)) AS net_total
FROM shop.orders o
JOIN shop.customer c ON c.id = o.customer_id
LEFT JOIN shop.order_line ol ON ol.order_id = o.id
GROUP BY o.id, c.display_name, o.order_date;

COMMENT ON TABLE shop.customer IS 'Registered customers';
COMMENT ON COLUMN shop.customer.status IS 'ACTIVE, SUSPENDED or CLOSED';
COMMENT ON VIEW shop.v_order_summary IS 'One row per order with totals';

