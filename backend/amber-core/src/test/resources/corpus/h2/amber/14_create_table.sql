CREATE TABLE constraints_demo (
    id INT CONSTRAINT pk_demo PRIMARY KEY,
    code VARCHAR(10) UNIQUE,
    code2 VARCHAR(10) CONSTRAINT uq_code2 UNIQUE NULLS DISTINCT,
    qty INT CHECK (qty >= 0),
    price DECIMAL(10, 2) CONSTRAINT chk_price CHECK (price > 0) NOT NULL,
    parent_id INT REFERENCES constraints_demo(id) ON DELETE CASCADE,
