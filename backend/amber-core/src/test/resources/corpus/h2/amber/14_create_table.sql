CREATE TABLE orders (
    id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    order_date DATE NOT NULL,
    status VARCHAR(20) DEFAULT 'NEW',
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT IF NOT EXISTS fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_orders UNIQUE (customer_id, order_date),
    CONSTRAINT chk_status CHECK (status IN ('NEW', 'PAID', 'SHIPPED')),
    UNIQUE NULLS NOT DISTINCT (status, order_date),
    UNIQUE NULLS ALL DISTINCT (customer_id, status),
    FOREIGN KEY (status) REFERENCES statuses (code) ON DELETE SET DEFAULT,
    CHECK (id > 0)
);
