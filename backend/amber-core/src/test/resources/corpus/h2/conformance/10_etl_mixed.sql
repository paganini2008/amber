-- Realistic H2 test-fixture / ETL script (typical Spring Boot schema.sql + data.sql flow)
DROP ALL OBJECTS;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS mart;

CREATE TABLE staging.raw_payment (
  payment_ref VARCHAR(40) NOT NULL,
  ledger_ref VARCHAR(20) NOT NULL,
  paid_on DATE NOT NULL,
  amount DECIMAL(12, 2) NOT NULL,
  currency CHAR(3) DEFAULT 'EUR',
  payload JSON
);

CREATE TABLE mart.account (
  account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ledger_ref VARCHAR(20) NOT NULL UNIQUE,
  opened_on DATE,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE mart.payment (
  payment_ref VARCHAR(40) PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES mart.account (account_id),
  paid_on DATE NOT NULL,
  amount DECIMAL(12, 2) NOT NULL,
  amount_eur DECIMAL(12, 2) GENERATED ALWAYS AS (CASE WHEN currency = 'EUR' THEN amount ELSE amount * 0.9 END),
  currency CHAR(3) NOT NULL
);

CREATE INDEX idx_payment_account_day ON mart.payment (account_id, paid_on);

