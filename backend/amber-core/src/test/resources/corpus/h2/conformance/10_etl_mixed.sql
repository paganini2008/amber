MERGE INTO mart.account (ledger_ref, opened_on) KEY (ledger_ref)
SELECT ledger_ref, MIN(paid_on) FROM staging.raw_payment GROUP BY ledger_ref;

MERGE INTO mart.payment AS t
USING (
  SELECT r.payment_ref, a.account_id, r.paid_on, r.amount, r.currency,
         ROW_NUMBER() OVER (PARTITION BY r.payment_ref ORDER BY r.paid_on DESC) AS rn
  FROM staging.raw_payment r JOIN mart.account a ON a.ledger_ref = r.ledger_ref
) AS s
ON t.payment_ref = s.payment_ref AND s.rn = 1
WHEN MATCHED THEN UPDATE SET amount = s.amount, currency = s.currency
WHEN NOT MATCHED AND s.rn = 1 THEN INSERT (payment_ref, account_id, paid_on, amount, currency)
  VALUES (s.payment_ref, s.account_id, s.paid_on, s.amount, s.currency);

CREATE VIEW mart.v_daily_balance AS
WITH daily AS (
  SELECT account_id, paid_on, SUM(amount_eur) AS day_total
  FROM mart.payment GROUP BY account_id, paid_on
)
SELECT account_id, paid_on, day_total,
       SUM(day_total) OVER (PARTITION BY account_id ORDER BY paid_on ROWS UNBOUNDED PRECEDING) AS running_total
FROM daily;

UPDATE mart.account a SET opened_on = (SELECT MIN(p.paid_on) FROM mart.payment p WHERE p.account_id = a.account_id)
WHERE EXISTS (SELECT 1 FROM mart.payment p WHERE p.account_id = a.account_id AND p.paid_on < a.opened_on);

DELETE FROM staging.raw_payment WHERE payment_ref IN (SELECT payment_ref FROM mart.payment);
SELECT account_id, paid_on, running_total FROM mart.v_daily_balance ORDER BY account_id, paid_on;
TRUNCATE TABLE staging.raw_payment;
DROP SCHEMA staging CASCADE;
