CREATE TABLE app.orders (
    order_id       BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1, NO CACHE, NO CYCLE),
    customer_id    INTEGER NOT NULL,
    order_date     DATE NOT NULL WITH DEFAULT CURRENT DATE,
    status         CHAR(1) NOT NULL DEFAULT 'N' CONSTRAINT ck_status CHECK (status IN ('N', 'P', 'S', 'C')),
    amount         DECIMAL(15, 2) DEFAULT 0 NOT NULL,
    discount       DECIMAL(5, 2) WITH DEFAULT,
    net_amount     DECIMAL(15, 2) GENERATED ALWAYS AS (amount - COALESCE(discount, 0)),
    note           VARCHAR(1000) INLINE LENGTH 200,
    created_by     VARCHAR(128) NOT NULL DEFAULT USER,
    created_ts     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    changed_ts     TIMESTAMP NOT NULL GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP IMPLICITLY HIDDEN,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_cust FOREIGN KEY (customer_id) REFERENCES app.customers (customer_id) ON DELETE RESTRICT ON UPDATE NO ACTION,
    CONSTRAINT uq_orders UNIQUE (customer_id, order_date, order_id),
    CHECK (amount >= 0)
) IN ts_data INDEX IN ts_idx LONG IN ts_lob;
CREATE TABLE app.customers (
    customer_id INTEGER NOT NULL PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    region_id SMALLINT REFERENCES app.regions (region_id) ON DELETE SET NULL,
    parent_id INTEGER CONSTRAINT fk_parent REFERENCES app.customers ON DELETE CASCADE NOT ENFORCED,
    id2 INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 10 MINVALUE 1000 MAXVALUE 99999 CYCLE CACHE 50 ORDER)
) ORGANIZE BY ROW;
CREATE TABLE app.fact_sales (
    sale_id BIGINT NOT NULL, sale_date DATE NOT NULL, store_id INT NOT NULL, amount DECIMAL(12, 2)
) ORGANIZE BY COLUMN IN ts_col DISTRIBUTE BY HASH (sale_id);
CREATE TABLE app.sales_part (
    sale_date DATE NOT NULL, region CHAR(2), amount DECIMAL(12, 2)
)
DISTRIBUTE BY HASH (region)
PARTITION BY RANGE (sale_date)
(PARTITION p2023 STARTING FROM ('2023-01-01') ENDING AT ('2023-12-31') INCLUSIVE IN ts_2023,
 PARTITION p2024 STARTING '2024-01-01' ENDING '2025-01-01' EXCLUSIVE IN ts_2024 INDEX IN ts_idx,
 PARTITION pmax STARTING ('2025-01-01') ENDING (MAXVALUE))
COMPRESS YES ADAPTIVE;
CREATE TABLE app.monthly (d DATE, v INT) PARTITION BY (d NULLS LAST) (STARTING '2024-01-01' ENDING '2024-12-31' EVERY 1 MONTH);
CREATE TABLE app.numparts (k INT, v INT) PARTITION BY RANGE (k) (STARTING 1 ENDING 1000 EVERY (100));
CREATE TABLE app.mdc (y INT, m INT, region CHAR(2), v INT) ORGANIZE BY DIMENSIONS (y, (m, region));
CREATE TABLE app.repl (id INT) DISTRIBUTE BY REPLICATION;
CREATE TABLE app.rnd (id INT) DISTRIBUTE BY RANDOM;
CREATE TABLE app.old_style (id INT) PARTITIONING KEY (id) USING HASHING;
CREATE TABLE app.compressed (id INT, txt VARCHAR(100)) COMPRESS YES STATIC VALUE COMPRESSION;
CREATE TABLE app.nocomp (id INT) COMPRESS NO NOT LOGGED INITIALLY;
CREATE TABLE app.cap (id INT) DATA CAPTURE CHANGES CCSID UNICODE APPEND ON VOLATILE CARDINALITY;
CREATE TABLE app.guarded (id INT) WITH RESTRICT ON DROP;
CREATE TABLE app.copy_of LIKE app.orders INCLUDING COLUMN DEFAULTS INCLUDING IDENTITY COLUMN ATTRIBUTES IN ts_data;
CREATE TABLE app.empty_copy AS (SELECT * FROM app.orders) WITH NO DATA;
CREATE TABLE app.filled_copy AS (SELECT order_id, amount FROM app.orders WHERE status = 'S') WITH DATA;
CREATE TABLE app.def_only AS (SELECT * FROM app.orders) DEFINITION ONLY;
CREATE TABLE IF NOT EXISTS app.maybe (id INT);
CREATE TABLE app.policy (
    id INT NOT NULL,
    premium DECIMAL(10, 2),
    bus_start DATE NOT NULL,
    bus_end DATE NOT NULL,
    sys_start TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW BEGIN,
    sys_end TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW END,
    trans_start TIMESTAMP(12) GENERATED ALWAYS AS TRANSACTION START ID IMPLICITLY HIDDEN,
    PERIOD SYSTEM_TIME (sys_start, sys_end),
    PERIOD BUSINESS_TIME (bus_start, bus_end),
    PRIMARY KEY (id, BUSINESS_TIME WITHOUT OVERLAPS)
);
CREATE TABLE app.lobs (id INT, doc CLOB(10M) NOT LOGGED COMPACT, pic BLOB(5M) LOGGED NOT COMPACT, x XML);
CREATE TABLE app.ks (k INT NOT NULL, v INT) ORGANIZE BY KEY SEQUENCE (k STARTING FROM 1 ENDING AT 1000) DISALLOW OVERFLOW PCTFREE 10;
CREATE TABLE app.insert_time (id INT) ORGANIZE BY INSERT TIME;
CREATE TABLE app.fk_attrs (a INT, b INT, FOREIGN KEY (a) REFERENCES app.p (a) NOT ENFORCED ENABLE QUERY OPTIMIZATION, CONSTRAINT c1 CHECK (b > 0) NOT ENFORCED TRUSTED);
