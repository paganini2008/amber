SELECT * FROM customer WHERE customer_id IN (SELECT customer_id FROM account_event WHERE amount > 100);
SELECT * FROM customer c WHERE EXISTS (SELECT 1 FROM account_event e WHERE e.customer_id = c.customer_id);
SELECT * FROM customer WHERE customer_id NOT IN (1, 2, 3);
SELECT * FROM (SELECT customer_id, sum(amount) AS total FROM account_event GROUP BY customer_id) t WHERE t.total > 50;
