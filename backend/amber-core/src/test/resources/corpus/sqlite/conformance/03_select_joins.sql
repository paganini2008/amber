SELECT c.display_name, e.amount FROM customer c INNER JOIN account_event e ON e.customer_id = c.customer_id;
SELECT c.display_name, e.amount FROM customer c LEFT OUTER JOIN account_event e USING (customer_id);
SELECT c.display_name, e.amount FROM customer c RIGHT JOIN account_event e ON e.customer_id = c.customer_id;
SELECT c.display_name, e.amount FROM customer c FULL OUTER JOIN account_event e ON e.customer_id = c.customer_id;
SELECT * FROM customer NATURAL JOIN account_event;
SELECT * FROM customer CROSS JOIN region;
SELECT * FROM customer, region WHERE region.code = 'EU';
