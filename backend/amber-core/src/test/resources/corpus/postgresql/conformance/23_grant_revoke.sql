-- Roles, GRANT, REVOKE, policies
CREATE ROLE report_role;
CREATE ROLE app_user WITH LOGIN PASSWORD 'change_me' VALID UNTIL '2030-01-01' CONNECTION LIMIT 10;
CREATE USER etl_user IN ROLE app_user NOSUPERUSER NOCREATEDB;
ALTER ROLE app_user SET search_path = sales, public;
ALTER USER etl_user WITH PASSWORD NULL;
GRANT SELECT ON sales.orders TO report_role;
GRANT SELECT, INSERT, UPDATE (status, amount), DELETE ON TABLE sales.orders TO app_user WITH GRANT OPTION;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA sales TO app_user;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA sales TO app_user;
GRANT EXECUTE ON FUNCTION sales.customer_total(bigint) TO PUBLIC;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA sales TO report_role;
GRANT USAGE ON SCHEMA sales TO report_role;
GRANT CREATE ON DATABASE analytics TO etl_user;
GRANT CONNECT, TEMPORARY ON DATABASE analytics TO report_role;
GRANT report_role TO etl_user WITH ADMIN OPTION;
GRANT report_role TO app_user WITH INHERIT FALSE, SET TRUE GRANTED BY postgres;
GRANT MAINTAIN ON sales.orders TO etl_user;
ALTER DEFAULT PRIVILEGES IN SCHEMA sales GRANT SELECT ON TABLES TO report_role;
ALTER DEFAULT PRIVILEGES FOR ROLE etl_user IN SCHEMA sales REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
REVOKE INSERT ON sales.orders FROM report_role;
REVOKE GRANT OPTION FOR SELECT ON sales.orders FROM app_user CASCADE;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
REVOKE report_role FROM etl_user;
CREATE POLICY tenant_isolation ON sales.orders USING (tenant_id = current_setting('app.tenant')::int);
CREATE POLICY ins_policy ON sales.orders AS RESTRICTIVE FOR INSERT TO app_user WITH CHECK (amount >= 0);
ALTER POLICY tenant_isolation ON sales.orders TO report_role;
DROP POLICY IF EXISTS ins_policy ON sales.orders;
ALTER TABLE sales.orders FORCE ROW LEVEL SECURITY;
REASSIGN OWNED BY etl_user TO postgres;
DROP OWNED BY etl_user CASCADE;
DROP ROLE IF EXISTS etl_user, report_role;
