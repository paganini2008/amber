SELECT * FROM sales.customer;
SELECT DISTINCT region_code FROM sales.customer;
SELECT DISTINCT ON (customer_id) customer_id, order_date, amount FROM sales.orders ORDER BY customer_id, order_date DESC;
SELECT customer_id, amount * 1.2 AS gross FROM sales.orders WHERE amount BETWEEN 10 AND 100 AND status IN ('NEW','OPEN');
SELECT * FROM sales.orders WHERE note LIKE 'A%' OR note ILIKE '%x%' OR note NOT LIKE '%_y' ESCAPE '\';
SELECT * FROM sales.orders WHERE note ~ '^[A-Z]' OR note ~* 'abc' OR note !~ 'z$' OR note SIMILAR TO '(a|b)%';
SELECT * FROM sales.orders WHERE shipped_at IS NULL OR shipped_at IS NOT NULL;
SELECT * FROM sales.orders WHERE a IS DISTINCT FROM b AND c IS NOT DISTINCT FROM d;
SELECT * FROM sales.orders WHERE flag IS TRUE OR flag IS NOT FALSE OR flag IS UNKNOWN;
SELECT * FROM sales.orders ORDER BY amount DESC NULLS LAST, order_id ASC NULLS FIRST LIMIT 10 OFFSET 20;
SELECT * FROM sales.orders ORDER BY 1 OFFSET 5 ROWS FETCH FIRST 10 ROWS ONLY;
SELECT * FROM sales.orders ORDER BY amount FETCH FIRST 3 ROWS WITH TIES;
SELECT * FROM sales.orders LIMIT ALL;
SELECT CASE WHEN amount > 100 THEN 'big' WHEN amount > 10 THEN 'mid' ELSE 'small' END AS bucket FROM sales.orders;
SELECT CASE status WHEN 'A' THEN 1 ELSE 0 END FROM sales.orders;
SELECT COALESCE(note, ''), NULLIF(amount, 0), GREATEST(a, b), LEAST(a, b) FROM sales.orders;
SELECT order_id FROM sales.orders FOR UPDATE;
SELECT order_id FROM sales.orders FOR UPDATE SKIP LOCKED;
SELECT order_id FROM sales.orders o FOR NO KEY UPDATE OF o NOWAIT;
SELECT order_id FROM sales.orders FOR SHARE;
SELECT order_id FROM sales.orders FOR KEY SHARE;
SELECT 1 WHERE EXISTS (SELECT 1);
SELECT extract(year FROM order_date), date_part('month', order_date), date_trunc('week', order_date) FROM sales.orders;
SELECT substring(note FROM 2 FOR 3), position('x' IN note), trim(both ' ' FROM note), overlay(note placing 'ab' from 2 for 2) FROM sales.orders;
SELECT note || '-' || order_id::text, concat_ws(',', a, b), format('%s-%I', a, b) FROM sales.orders;
SELECT * FROM ONLY sales.orders;
SELECT * FROM sales.orders TABLESAMPLE SYSTEM (10) REPEATABLE (42);
SELECT * FROM sales.orders TABLESAMPLE BERNOULLI (5);
