-- DDL: tables, constraints, identity, generated, partitioning
CREATE SCHEMA IF NOT EXISTS sales AUTHORIZATION app_owner;
CREATE TABLE sales.region (code char(2) PRIMARY KEY, name text NOT NULL UNIQUE, active boolean NOT NULL DEFAULT true);
CREATE TABLE IF NOT EXISTS sales.customer (
  customer_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name varchar(200) NOT NULL,
  email text CONSTRAINT customer_email_chk CHECK (email LIKE '%@%'),
  region_code char(2) REFERENCES sales.region (code) ON DELETE SET NULL ON UPDATE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  credit numeric(12,2) DEFAULT 0 CHECK (credit >= 0),
  full_label text GENERATED ALWAYS AS (name || ' <' || coalesce(email, '') || '>') STORED,
  CONSTRAINT customer_name_uq UNIQUE (name, region_code)
);
CREATE TABLE sales.orders (
  order_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000 INCREMENT BY 1 CACHE 20),
  customer_id bigint NOT NULL,
  order_date date NOT NULL,
  amount numeric(12,2),
  PRIMARY KEY (order_id, order_date),
  FOREIGN KEY (customer_id) REFERENCES sales.customer (customer_id) DEFERRABLE INITIALLY DEFERRED,
  EXCLUDE USING gist (customer_id WITH =, daterange(order_date, order_date + 1) WITH &&)
) PARTITION BY RANGE (order_date);
CREATE TABLE sales.orders_2024 PARTITION OF sales.orders FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TABLE sales.orders_old PARTITION OF sales.orders FOR VALUES FROM (MINVALUE) TO ('2024-01-01');
CREATE TABLE sales.orders_default PARTITION OF sales.orders DEFAULT;
CREATE TABLE sales.events (id bigint, kind text) PARTITION BY LIST (kind);
CREATE TABLE sales.events_click PARTITION OF sales.events FOR VALUES IN ('click', 'tap');
CREATE TABLE sales.hashed (id bigint) PARTITION BY HASH (id);
CREATE TABLE sales.hashed_0 PARTITION OF sales.hashed FOR VALUES WITH (MODULUS 4, REMAINDER 0);
CREATE TABLE sales.events_view PARTITION OF sales.events (kind DEFAULT 'view') FOR VALUES IN ('view') PARTITION BY RANGE (id);
CREATE TABLE sales.orders_like (LIKE sales.orders INCLUDING ALL EXCLUDING INDEXES);
CREATE TABLE sales.child_tbl (extra int) INHERITS (sales.region);
