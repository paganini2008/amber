"""Regenerates the keyword section of Db2Lexer.g4 and the non_reserved_keyword rule of Db2Parser.g4.

Usage: python3 tools/generate_keywords.py   (run from anywhere)

Every upper-case token referenced by Db2Parser.g4 that is not a literal/operator token becomes a
keyword token 'NAME' in Db2Lexer.g4. All keywords except RESERVED and the words listed in the
parser rule alias_restricted_keyword are emitted into non_reserved_keyword, so they stay usable
as identifiers. Edit RESERVED below to reserve or un-reserve a word.
"""
import re, sys, os
d = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..',
    'src', 'main', 'antlr4', 'com', 'github', 'amber', 'dialect', 'db2', 'grammar')
P = d + '/Db2Parser.g4'
L = d + '/Db2Lexer.g4'
p = open(P).read()
marker = '// @@NON_RESERVED@@'
body = p.split(marker)[0] if marker in p else p.split('// ----- generated: non_reserved_keyword -----')[0]
# strip comments and literal strings
b = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
b = re.sub(r'//[^\n]*', '', b)
b = re.sub(r"'[^']*'", '', b)
toks = set(re.findall(r'\b([A-Z][A-Z0-9_]*)\b', b))
NONKW = {'IDENTIFIER', 'QUOTED_IDENTIFIER', 'STRING', 'HEX_STRING', 'BINARY_STRING', 'GRAPHIC_STRING',
 'HEX_GRAPHIC_STRING', 'UNICODE_STRING', 'INTEGER_LITERAL', 'DECIMAL_LITERAL', 'FLOAT_LITERAL',
 'CONCAT_OP', 'ARROW', 'NEQ', 'LE', 'GE', 'EQ', 'LT', 'GT', 'PLUS', 'MINUS_SIGN', 'STAR', 'SLASH',
 'QUESTION', 'COLON', 'SEMI', 'COMMA', 'DOT', 'LPAREN', 'RPAREN', 'LBRACKET', 'RBRACKET', 'EOF'}
kws = sorted(toks - NONKW)
# Words that can never be identifiers unless delimited ("..."). A subset of the Db2 reserved
# words: the ones whose use as a name would make the grammar ambiguous.
RESERVED = set('''ALL AND ANY AS BETWEEN BY CASE CAST CHECK CONCAT CONNECT_BY_ROOT CONSTRAINT CROSS
CURRENT DEFAULT DELETE DISTINCT ELSE ELSEIF END EXCEPT EXISTS FETCH FOR FOREIGN FROM FULL GROUP
HAVING IF IN INNER INSERT INTERSECT INTO IS JOIN LATERAL LEFT LIKE MERGE NOT NULL OF ON OR ORDER
OUTER PRIMARY PRIOR RIGHT SELECT SET SOME TABLE THEN UNION UNIQUE UPDATE USING VALUES WHEN WHERE
WITH'''.split())
m = re.search(r'alias_restricted_keyword\s*:(.*?);', body, re.S)
RESTRICTED = set(re.findall(r'[A-Z_][A-Z0-9_]*', m.group(1)))
nonres = [k for k in kws if k not in RESERVED and k not in RESTRICTED]
missing = RESERVED - set(kws)
if missing: print('reserved but unused:', sorted(missing))
lines = []
for i in range(0, len(nonres), 6):
    lines.append(' | '.join(nonres[i:i+6]))
rule = ('// ----- generated: non_reserved_keyword -----\n'
        '// Keywords that this grammar does not reserve and that therefore remain usable as\n'
        '// identifiers (generated by tools/generate_keywords.py).\n'
        'non_reserved_keyword\n    : ' + '\n    | '.join(lines) + '\n    ;\n')
open(P, 'w').write(body.rstrip() + '\n\n' + rule)
l = open(L).read()
start = '// ----- generated: keywords -----'
end = '// ----- end generated: keywords -----'
# Token names that would clash with constants of the generated Java lexer.
def text(k):
    return {'SKIP_': 'SKIP', 'MODE_': 'MODE', 'HIDDEN_': 'HIDDEN'}.get(k, k)
kwlines = '\n'.join(f"{k:<24}: '{text(k)}';" for k in kws)
pre, rest = l.split(start)
_, post = rest.split(end)
open(L, 'w').write(pre + start + '\n' + kwlines + '\n' + end + post)
print(len(kws), 'keywords;', len(nonres), 'non-reserved')
